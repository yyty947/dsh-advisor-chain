export type Translate = (key: ClientKey, params?: Record<string, string | number | undefined>) => string;

/** Stand-in used until the host's locale service binds the namespace (and in tests). */
export function fallbackTranslate(key: ClientKey, params?: Record<string, string | number | undefined>): string {
  const template = zh[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name] ?? "") : match));
}
